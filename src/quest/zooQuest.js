export function getEnding(solvedCount, totalTasks) {
  if (totalTasks > 0 && solvedCount >= totalTasks) return FINAL_ENDING;
  return ENDINGS.filter((ending) => solvedCount >= ending.minSolved).at(-1);
}

// Подставляет имя участника в текст брифинга
export function personalize(text, name) {
  return text.replaceAll('{name}', name || 'Стажёр');
}
