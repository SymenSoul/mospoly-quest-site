export function personalize(text, name) {
  return text.replaceAll('{name}', name || 'участник');
}

export function getOrlovEnding(solvedCount, totalTasks) {
  const full = totalTasks > 0 && solvedCount >= totalTasks;
  if (full) {
    return {
      isFinal: true,
      title: 'Орлов найден',
      text: 'Все цифровые следы восстановлены. Орлов изолировал рабочую среду, чтобы остановить утечку данных. Расследование завершено — теперь ищите своё имя в рейтинге.',
    };
  }
  if (solvedCount > 0) {
    return {
      isFinal: false,
      title: 'Расследование приостановлено',
      text: `Удалось подтвердить ${solvedCount} из ${totalTasks} улик. Дело остаётся открытым, но результат сохранён в рейтинге.`,
    };
  }
  return {
    isFinal: false,
    title: 'След пока не найден',
    text: 'Расследование завершено до подтверждения улик. Можно вернуться к делу позже — результат этой смены сохранён.',
  };
}
